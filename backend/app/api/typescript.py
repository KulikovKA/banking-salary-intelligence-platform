"""Deterministic OpenAPI component -> TypeScript generator, with drift verification.

Run: PYTHONPATH=backend uv run python -m app.api.typescript [--check]
No network, npm generator or extra dependencies are required.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any


def type_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "", name)


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    for keyword, join in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if keyword in schema:
            return "(" + join.join(ts_type(item) for item in schema[keyword]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", ()))
        lines = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
            for name, value in sorted(schema.get("properties", {}).items())
        ]
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            lines.append(f"[key: string]: {ts_type(extra)};")
        elif extra is True:
            lines.append("[key: string]: unknown;")
        return "{ " + " ".join(lines) + " }" if lines else "Record<string, never>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def render_typescript(openapi: dict[str, Any]) -> str:
    canonical = json.dumps(openapi, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    revision = hashlib.sha256(canonical.encode()).hexdigest()
    lines = [
        "// Generated by app.api.typescript from actual FastAPI OpenAPI. Do not edit.",
        "// UUID, date and UTC timestamp wire values are strings. Decimal values stay strings.",
        f'export const API_CONTRACT_REVISION = "{revision}" as const;',
        'export type BankCode = "sber" | "vtb" | "alfa" | "kuban_credit";',
    ]
    for name, schema in sorted(openapi["components"]["schemas"].items()):
        lines.append(f"export type {type_name(name)} = {ts_type(schema)};")
    lines.extend(
        [
            "export type Scenario = ScenarioInput;",
            "export type ApiEndpoints = {",
        ]
    )
    for path, operations in sorted(openapi["paths"].items()):
        for method, operation in sorted(operations.items()):
            if method not in {"get", "post", "patch", "put", "delete"}:
                continue
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {})
            params = operation.get("parameters", [])
            query: dict[str, Any] = {"type": "object", "properties": {}, "required": []}
            for param in params:
                if param["in"] in {"query", "path"}:
                    query["properties"][param["name"]] = param["schema"]
                    if param.get("required"):
                        query["required"].append(param["name"])
            success: dict[str, Any] = next(
                (value for code, value in operation["responses"].items() if code.startswith("2")),
                {},
            )
            response = success.get("content", {}).get("application/json", {})
            response_type = ts_type(response["schema"]) if "schema" in response else "ArrayBuffer"
            lines.append(
                f'  "{method.upper()} {path}": {{ '
                f"request: {ts_type(body['schema']) if 'schema' in body else 'never'}; "
                f"parameters: {ts_type(query)}; response: {response_type}; error: ApiError; }};"
            )
    lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> None:
    from app.main import app

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[3] / "frontend/lib/api-contracts.ts"
    rendered = render_typescript(app.openapi())
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != rendered:
            raise SystemExit("API_TYPESCRIPT_DRIFT")
        print("OpenAPI/TypeScript contract: PASS")
    else:
        path.write_text(rendered, encoding="utf-8", newline="\n")
        print("Generated frontend/lib/api-contracts.ts")


if __name__ == "__main__":
    main()
